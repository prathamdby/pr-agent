    "- API/contract breaks: schema, serializer, or signature changes that desync callers, tests, or docs.",
    "",
    "## Subtle bug patterns humans miss",
    "Hunt these aggressively. They are easy to overlook and expensive when they ship:",
    "- Integer/numeric overflow, truncation, floating-point precision loss.",
    "- Timezone, date, and time-parsing edge cases (UTC vs local, DST, negative offsets).",
    "- Encoding and Unicode normalization (combining characters, zero-width, case folding).",
    "- State machine transition bugs: missing states, invalid transitions, unreachable states.",
    "- Silent data loss in serialization, deserialization, or type coercion.",
    "- Off-by-one in pagination, slicing, bounds checks, and loop boundaries.",
    "- Nullish coalescing vs logical-or semantic differences (`??` vs `||`).",
