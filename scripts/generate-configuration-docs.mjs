#!/usr/bin/env node
/**
 * Generate (or --check) the env-var inventory section in docs/configuration.md
 * from src/settings/envKeys.ts.
 */
import fs from "node:fs";
import path from "node:path";

const ROOT = process.cwd();
const DOC = path.join(ROOT, "docs", "configuration.md");
const ENV_KEYS = path.join(ROOT, "src", "settings", "envKeys.ts");
const BEGIN = "<!-- BEGIN GENERATED ENV CATALOG -->";
const END = "<!-- END GENERATED ENV CATALOG -->";

function parseEnvKeys(source) {
  const keys = [];
  const re = /^\s*([A-Z][A-Z0-9_]+):\s*"([A-Z][A-Z0-9_]+)"/gm;
  let m;
  while ((m = re.exec(source))) {
    keys.push(m[2]);
  }
  return [...new Set(keys)];
}

function renderSection(keys) {
  const rows = keys
    .toSorted((a, b) => a.localeCompare(b))
    .map((k) => `| \`${k}\` |`)
    .join("\n");
  return [
    BEGIN,
    "",
    "> Generated by `scripts/generate-configuration-docs.mjs` from `src/settings/envKeys.ts`.",
    "> Do not hand-edit between the markers; run `nub run docs:config` (or `--check` in CI).",
    "",
    "| Env var |",
    "| ------- |",
    rows,
    "",
    END,
  ].join("\n");
}

const keys = parseEnvKeys(fs.readFileSync(ENV_KEYS, "utf8"));
if (keys.length < 10) {
  console.error("Failed to parse env keys from envKeys.ts");
  process.exit(1);
}

const section = renderSection(keys);
const check = process.argv.includes("--check");
let doc = fs.readFileSync(DOC, "utf8");

if (check) {
  if (!doc.includes(BEGIN) || !doc.includes(END)) {
    console.error("docs/configuration.md missing generated env catalog markers");
    process.exit(1);
  }
  const start = doc.indexOf(BEGIN);
  const end = doc.indexOf(END) + END.length;
  const body = doc.slice(start, end);
  const missing = keys.filter((k) => !body.includes(`\`${k}\``));
  if (missing.length) {
    console.error(
      `docs/configuration.md generated catalog missing keys:\n${missing.map((k) => `- ${k}`).join("\n")}`,
    );
    process.exit(1);
  }
  // Extra keys inside catalog that are not in envKeys are allowed only if none.
  const catalogKeys = [...body.matchAll(/`([A-Z][A-Z0-9_]+)`/g)].map((m) => m[1]);
  const extra = catalogKeys.filter((k) => !keys.includes(k));
  // Filter prose words that aren't env keys - only ALL_CAPS with underscore or single tokens we know
  const realExtra = extra.filter((k) => k.includes("_") || keys.includes(k));
  const unexpected = realExtra.filter((k) => !keys.includes(k));
  if (unexpected.length) {
    console.error(
      `docs/configuration.md catalog has unexpected keys:\n${unexpected.map((k) => `- ${k}`).join("\n")}`,
    );
    process.exit(1);
  }
  console.log(`Generated env catalog check passed (${keys.length} keys).`);
  process.exit(0);
}

if (!doc.includes(BEGIN) || !doc.includes(END)) {
  doc = `${doc.trimEnd()}\n\n## Generated env catalog\n\n${section}\n`;
  fs.writeFileSync(DOC, doc);
  console.log(`Wrote generated env catalog (${keys.length} keys).`);
  process.exit(0);
}

const next = doc.replace(new RegExp(`${BEGIN}[\\s\\S]*?${END}`), () => section);
if (next !== doc) {
  fs.writeFileSync(DOC, next);
  console.log(`Updated generated env catalog (${keys.length} keys).`);
} else {
  console.log("Generated env catalog already up to date.");
}
